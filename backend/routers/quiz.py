"""
DataSip Quiz Router
Endpoints: generate quiz, get quiz, submit answers, quiz history.
"""
import json
from typing import List
from fastapi import APIRouter, Depends, HTTPException, status
from sqlalchemy.orm import Session
from datetime import datetime
from backend.database import get_db
from backend import models, schemas
from backend.auth import get_current_user
from backend.services import gemini_service
from backend.services.quiz_service import grade_quiz, save_quiz_attempt

router = APIRouter(prefix="/api/quiz", tags=["Quiz"])


@router.post("/generate", response_model=schemas.QuizResponse, status_code=201)
def generate_quiz(
    request: schemas.QuizGenerateRequest,
    db: Session = Depends(get_db),
    current_user: models.User = Depends(get_current_user),
):
    """
    Generate a new AI-powered quiz on the requested topic.
    Questions are generated by Gemini and stored in the database.
    """
    # Call Gemini to generate quiz content
    quiz_data = gemini_service.generate_quiz(
        topic=request.topic,
        difficulty=request.difficulty,
        num_questions=request.num_questions,
        question_type=request.question_type,
    )

    if not quiz_data or "questions" not in quiz_data:
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail="Failed to generate quiz. Please try again.",
        )

    # Create Quiz record
    quiz = models.Quiz(
        user_id=current_user.id,
        topic=request.topic,
        difficulty=request.difficulty,
        num_questions=len(quiz_data["questions"]),
        question_type=request.question_type,
    )
    db.add(quiz)
    db.flush()  # Get quiz.id

    # Create Question records
    for idx, q_data in enumerate(quiz_data["questions"]):
        question = models.Question(
            quiz_id=quiz.id,
            question_text=q_data.get("question_text", ""),
            question_type=q_data.get("question_type", request.question_type),
            correct_answer=q_data.get("correct_answer", ""),
            explanation=q_data.get("explanation", ""),
            order_index=idx,
        )
        question.options = q_data.get("options", [])
        db.add(question)

    db.commit()
    db.refresh(quiz)

    # Build response (hide correct answers and explanations)
    questions_resp = []
    for q in sorted(quiz.questions, key=lambda x: x.order_index):
        questions_resp.append(
            schemas.QuestionResponse(
                id=q.id,
                question_text=q.question_text,
                question_type=q.question_type,
                options=q.options,
                order_index=q.order_index,
            )
        )

    return schemas.QuizResponse(
        id=quiz.id,
        topic=quiz.topic,
        difficulty=quiz.difficulty,
        num_questions=quiz.num_questions,
        question_type=quiz.question_type,
        created_at=quiz.created_at,
        questions=questions_resp,
    )


@router.get("/history", response_model=List[schemas.QuizHistoryItem])
def get_quiz_history(
    limit: int = 20,
    db: Session = Depends(get_db),
    current_user: models.User = Depends(get_current_user),
):
    """Get the user's quiz attempt history."""
    attempts = (
        db.query(models.QuizAttempt)
        .join(models.Quiz)
        .filter(models.QuizAttempt.user_id == current_user.id)
        .order_by(models.QuizAttempt.completed_at.desc())
        .limit(limit)
        .all()
    )

    result = []
    for attempt in attempts:
        result.append(
            schemas.QuizHistoryItem(
                attempt_id=attempt.id,
                quiz_id=attempt.quiz_id,
                topic=attempt.quiz.topic,
                difficulty=attempt.quiz.difficulty,
                score=attempt.score,
                correct_count=attempt.correct_count,
                total_questions=attempt.total_questions,
                completed_at=attempt.completed_at,
            )
        )
    return result


@router.get("/{quiz_id}", response_model=schemas.QuizResponse)
def get_quiz(
    quiz_id: int,
    db: Session = Depends(get_db),
    current_user: models.User = Depends(get_current_user),
):
    """Get a specific quiz by ID (without answers)."""
    quiz = (
        db.query(models.Quiz)
        .filter(
            models.Quiz.id == quiz_id,
            models.Quiz.user_id == current_user.id,
        )
        .first()
    )

    if not quiz:
        raise HTTPException(status_code=404, detail="Quiz not found")

    questions_resp = []
    for q in sorted(quiz.questions, key=lambda x: x.order_index):
        questions_resp.append(
            schemas.QuestionResponse(
                id=q.id,
                question_text=q.question_text,
                question_type=q.question_type,
                options=q.options,
                order_index=q.order_index,
            )
        )

    return schemas.QuizResponse(
        id=quiz.id,
        topic=quiz.topic,
        difficulty=quiz.difficulty,
        num_questions=quiz.num_questions,
        question_type=quiz.question_type,
        created_at=quiz.created_at,
        questions=questions_resp,
    )


@router.post("/{quiz_id}/submit", response_model=schemas.QuizSubmitResponse)
def submit_quiz(
    quiz_id: int,
    submission: schemas.QuizSubmitRequest,
    db: Session = Depends(get_db),
    current_user: models.User = Depends(get_current_user),
):
    """
    Submit answers for a quiz. Auto-grades and stores the result.
    Returns per-question feedback with explanations.
    """
    quiz = (
        db.query(models.Quiz)
        .filter(
            models.Quiz.id == quiz_id,
            models.Quiz.user_id == current_user.id,
        )
        .first()
    )

    if not quiz:
        raise HTTPException(status_code=404, detail="Quiz not found")

    if not quiz.questions:
        raise HTTPException(status_code=400, detail="Quiz has no questions")

    # Grade the quiz
    grade_result = grade_quiz(
        quiz=quiz,
        answers=submission.answers,
        db=db,
        user=current_user,
    )

    # Save the attempt and update topic progress
    attempt = save_quiz_attempt(
        quiz=quiz,
        user=current_user,
        grade_result=grade_result,
        answers=submission.answers,
        time_taken_seconds=submission.time_taken_seconds,
        db=db,
    )

    # Build result items
    result_items = [
        schemas.QuizResultQuestion(**r) for r in grade_result["results"]
    ]

    return schemas.QuizSubmitResponse(
        attempt_id=attempt.id,
        quiz_id=quiz.id,
        topic=quiz.topic,
        score=grade_result["score"],
        correct_count=grade_result["correct_count"],
        total_questions=grade_result["total_questions"],
        time_taken_seconds=submission.time_taken_seconds,
        results=result_items,
        completed_at=attempt.completed_at,
    )
